const state = {
  lang: "fr",
  filter: "all"
};

const projectsGrid = document.getElementById("projects-grid");
const langButtons = document.querySelectorAll(".lang-btn");
const filterButtons = document.querySelectorAll(".filter-btn");

function renderProjects() {
  const visible = projects.filter((project) => {
    if (state.filter === "all") {
      return true;
    }
    return project.tags.includes(state.filter);
  });

  projectsGrid.innerHTML = visible
    .map(
      (project) => `
        <article class="project-card">
          <div class="project-top">
            <div>
              <p class="eyebrow">${project.id}</p>
              <h3>${project.title[state.lang]}</h3>
            </div>
            <span class="project-tag">${translations[state.lang]["project.available"]}</span>
          </div>
          <p>${project.description[state.lang]}</p>
          <div class="project-meta">
            ${project.meta.map((item) => `<span class="meta-chip">${item}</span>`).join("")}
          </div>
          <div class="project-highlights">
            <div class="project-highlight">
              <span>${translations[state.lang]["project.roleLabel"]}</span>
              <strong>${project.role[state.lang]}</strong>
            </div>
            <div class="project-highlight">
              <span>${translations[state.lang]["project.businessValueLabel"]}</span>
              <strong>${project.businessValue[state.lang]}</strong>
            </div>
          </div>
          <div class="project-links">
            <a class="primary-btn" href="${project.github}" target="_blank" rel="noreferrer">GitHub</a>
            <a class="secondary-btn" href="${project.caseLink}">${translations[state.lang]["project.caseStudy"]}</a>
          </div>
        </article>
      `
    )
    .join("");
}

function applyLanguage(lang) {
  state.lang = lang;
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.getAttribute("data-i18n");
    const value = translations[lang][key];
    if (value) {
      element.textContent = value;
    }
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const key = element.getAttribute("data-i18n-alt");
    const value = translations[lang][key];
    if (value) {
      element.setAttribute("alt", value);
    }
  });

  langButtons.forEach((button) => {
    button.classList.toggle("active", button.dataset.lang === lang);
  });

  renderProjects();
}

langButtons.forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.lang));
});

filterButtons.forEach((button) => {
  button.addEventListener("click", () => {
    state.filter = button.dataset.filter;
    filterButtons.forEach((item) => item.classList.toggle("active", item === button));
    renderProjects();
  });
});

applyLanguage("fr");
